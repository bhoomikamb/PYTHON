print("----------------------------EVEN NUMBER GENERATOR------------------------------------------")
print("===========================================================================================")
def even_numbers(n):
    for i in range(1,n+1):
        if i%2==0:
            yield i
even=even_numbers(50)
print("Even:",even)
print("------------------------------------------------------------------------------------------")

print("==========================================================================================")
print("---------------------------------SQUARE GENERATOR-----------------------------------------")
print("==========================================================================================")
def square_generator(n):
    for i in range(1,n+1):
        yield i**2
for num in square_generator(15):
    print("Square numbers:",num)
print("------------------------------------------------------------------------------------------")

