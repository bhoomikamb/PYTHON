print("-------------------------------------SQUARE FUNCTION----------------------------------------")
print("============================================================================================")
def power(base,exponent):
    return base**exponent
square=partial(power,exponent=2)
print(square(4))
print(square(10))
print(square(2))
print(square(17))
print("-------------------------------------------------------------------------------------------")

