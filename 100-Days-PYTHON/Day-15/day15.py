#===========================================================================================
#-------------------------------FLEXIBLE NUMBER CALCULATOR----------------------------------
#===========================================================================================
def calculator_sum(*args):
    total=0
    for i in args:
        total+=i
    return total
print(calculator_sum(10,20,30,40))
print(calculator_sum(14,25,36,75))
print("-------------------------------------------------------------------------------------")

