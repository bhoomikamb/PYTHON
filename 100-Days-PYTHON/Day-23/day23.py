print("==================================================================================================")
@lru_cache
def fibonacci(n):
    if n<2:
        return n
    return fibonacci(n-1)+fibonacci(n-2)
print(fibonacci(10))
print(fibonacci(17))
print(fibonacci(2))
print(fibonacci.cache_info())
print("-------------------------------------------------------------------------------------------------")

